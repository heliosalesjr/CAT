#!/usr/bin/env node
/**
 * Reads the live schema and writes src/lib/db/schema.ts.
 *
 *   DATABASE_URL=postgres://... node db/types.mjs [--check]
 *
 *   --check  regenerate in memory and exit non-zero if the file on disk
 *            differs — for CI, so a migration that lands without the types
 *            being regenerated fails loudly instead of drifting.
 *
 * Why generate instead of hand-writing: the whole point of the data layer is
 * that a renamed column becomes a TypeScript error rather than `undefined` in
 * production. A hand-written type cannot do that, because nothing checks it
 * against the database. This script is the check.
 *
 * It is not an ORM and does not want to be one. CLAUDE.md rules those out and
 * the reasoning holds: it emits types and nothing else — no query builder, no
 * runtime, no opinion about how you select.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import pg from 'pg';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, '..', 'src', 'lib', 'db', 'schema.ts');
const check = process.argv.includes('--check');

const url = process.env.DATABASE_URL;
if (!url) {
  console.error('DATABASE_URL is not set. Point it at a migrated database and retry.');
  process.exit(1);
}

// Owned by @auth/pg-adapter, queried only by Auth.js, and camelCase on
// purpose. Typing them here would invite somebody to use them directly.
const AUTH_TABLES = new Set(['users', 'accounts', 'sessions', 'verification_token']);
const SKIP = new Set([...AUTH_TABLES, 'schema_migrations']);

const client = new pg.Client({
  connectionString: url,
  ssl: url.includes('localhost') ? undefined : { rejectUnauthorized: true },
});
await client.connect();

const { rows: enumRows } = await client.query(`
  SELECT t.typname AS name, e.enumlabel AS label
  FROM   pg_type t
  JOIN   pg_enum e ON e.enumtypid = t.oid
  JOIN   pg_namespace n ON n.oid = t.typnamespace AND n.nspname = 'public'
  ORDER  BY t.typname, e.enumsortorder`);

const { rows: colRows } = await client.query(`
  SELECT c.table_name, c.column_name, c.is_nullable, c.udt_name, c.ordinal_position,
         t.table_type, c.column_default
  FROM   information_schema.columns c
  JOIN   information_schema.tables  t
         ON t.table_schema = c.table_schema AND t.table_name = c.table_name
  WHERE  c.table_schema = 'public'
  ORDER  BY c.table_name, c.ordinal_position`);

await client.end();

const enums = new Map();
for (const r of enumRows) {
  if (!enums.has(r.name)) enums.set(r.name, []);
  enums.get(r.name).push(r.label);
}

const pascal = (s) => s.replace(/(^|_)([a-z0-9])/g, (_, __, ch) => ch.toUpperCase());
const camel = (s) => s.replace(/_([a-z0-9])/g, (_, ch) => ch.toUpperCase());

/**
 * One place where a Postgres type becomes a TypeScript one. Three of these
 * are deliberate and documented in client.ts, which installs the matching
 * runtime parsers — change them together or the types start lying:
 *
 *   date      -> string   a date with no time is 'YYYY-MM-DD'. node-postgres
 *                         would hand back a Date at LOCAL midnight, which
 *                         moves `available_from` across a day boundary
 *                         depending on where the server runs.
 *   numeric   -> number   every numeric in this schema is a small display
 *                         value (a 0-5 rating, a day count). Money is `int`
 *                         USD. If that ever stops being true, stop parsing.
 *   int8      -> string   bigserial ids. Converting risks precision, and
 *                         nothing does arithmetic on them.
 */
function tsType(udt) {
  if (udt.startsWith('_')) return `${tsType(udt.slice(1))}[]`;
  if (enums.has(udt)) return pascal(udt);
  switch (udt) {
    case 'text': case 'varchar': case 'bpchar': case 'name': case 'uuid':
    case 'inet': case 'cidr': case 'macaddr': case 'interval': case 'bytea':
      return 'string';
    case 'date':                               return 'string';
    case 'int8':                               return 'string';
    case 'int2': case 'int4': case 'float4': case 'float8': case 'numeric':
      return 'number';
    case 'bool':                               return 'boolean';
    case 'timestamptz': case 'timestamp': case 'timetz': case 'time':
      return 'Date';
    case 'json': case 'jsonb':                 return 'Json';
    default:                                   return 'unknown';
  }
}

const tables = new Map();
for (const c of colRows) {
  if (SKIP.has(c.table_name)) continue;
  if (!tables.has(c.table_name)) {
    tables.set(c.table_name, { kind: c.table_type, cols: [] });
  }
  tables.get(c.table_name).cols.push(c);
}

const out = [];
out.push(`// Generated by db/types.mjs from the live schema. Do not edit.`);
out.push(`// Regenerate with \`npm run db:types\` after every migration;`);
out.push(`// \`npm run db:types:check\` fails if this file has drifted.`);
out.push(`//`);
out.push(`// ${tables.size} relations, ${enums.size} enums.`);
out.push('');
out.push(`export type Json =`);
out.push(`  | string | number | boolean | null`);
out.push(`  | { [key: string]: Json } | Json[];`);
out.push('');
out.push(`/** snake_case keys as Postgres returns them, camelCase as the app uses them. */`);
out.push(`export type SnakeToCamel<S extends string> =`);
out.push(`  S extends \`\${infer H}_\${infer T}\``);
out.push(`    ? \`\${H}\${Capitalize<SnakeToCamel<T>>}\``);
out.push(`    : S;`);
out.push('');
out.push(`export type Camelize<T> = { [K in keyof T as SnakeToCamel<K & string>]: T[K] };`);
out.push('');

out.push('// ' + '-'.repeat(74));
out.push('// Enums');
out.push('// ' + '-'.repeat(74));
out.push('');
for (const [name, labels] of [...enums].sort()) {
  out.push(`export type ${pascal(name)} =`);
  out.push(labels.map((l) => `  | ${JSON.stringify(l)}`).join('\n') + ';');
  out.push('');
}

out.push('// ' + '-'.repeat(74));
out.push('// Relations');
out.push('// ' + '-'.repeat(74));
out.push('');
for (const [name, { kind, cols }] of [...tables].sort()) {
  const type = `${pascal(name)}Row`;
  out.push(`/** ${kind === 'VIEW' ? 'View' : 'Table'} \`${name}\`. */`);
  out.push(`export type ${type} = {`);
  for (const c of cols) {
    const optional = c.is_nullable === 'YES' ? ' | null' : '';
    out.push(`  ${c.column_name}: ${tsType(c.udt_name)}${optional};`);
  }
  out.push('};');
  out.push('');
}

const text = out.join('\n').replace(/\n{3,}/g, '\n\n') + '\n';

if (check) {
  let current = '';
  try { current = readFileSync(OUT, 'utf8'); } catch { /* missing counts as drift */ }
  if (current !== text) {
    console.error('src/lib/db/schema.ts is out of date. Run `npm run db:types`.');
    process.exit(1);
  }
  console.log(`Types are current — ${tables.size} relations, ${enums.size} enums.`);
  process.exit(0);
}

writeFileSync(OUT, text);
console.log(`Wrote src/lib/db/schema.ts — ${tables.size} relations, ${enums.size} enums.`);
